def _cmap():
    """Construye el colormap de matplotlib a partir de los bins de GIBS.

    Se arma la LUT a mano (en vez de `from_list`) para que cada valor caiga en el
    MISMO bin que en GIBS/Worldview: la tabla de GIBS es por rangos, no un degradado
    continuo, y en la mitad templada el paso es de 0.5 C.
    """
    import numpy as np
    from matplotlib.colors import ListedColormap

    n = 2048                       # ~0.07 C por entrada: no pierde los bins de 0.5 C
    span = VMAX - VMIN
    bordes = np.array([b[0] for b in BINS_GIBS])
    colores = np.array([b[2] for b in BINS_GIBS], dtype=float) / 255.0
    valores = VMIN + (np.arange(n) + 0.5) / n * span
    idx = np.clip(np.searchsorted(bordes, valores, side="right") - 1,
                  0, len(BINS_GIBS) - 1)
    return ListedColormap(colores[idx], name="gibs_clean_ir", N=n)


#: Colormap listo para usar (equivalente al de Worldview).
CMAP_GIBS_CLEAN_IR = _cmap()
